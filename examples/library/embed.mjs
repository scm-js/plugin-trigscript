// The library's modules, lib/*.ts, as text for plugin.ts to hand to TrigScript: run `node embed.mjs` after editing
// one. (A plugin cannot import a .ts file as text, so the modules travel in modules.ts.)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = import.meta.dirname, lib = join(root, "lib");
const walk = (dir) => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : /\.tsx?$/.test(f) ? [join(dir, f)] : []));
const modules = Object.fromEntries(walk(lib).sort().map((f) => [relative(lib, f).replace(/\\/g, "/"), readFileSync(f, "utf8")]));
writeFileSync(join(root, "modules.ts"), `// Generated by embed.mjs from lib/ — do not edit.\nexport const MODULES: Record<string, string> = ${JSON.stringify(modules, null, 1)};\n`);
console.log(`modules.ts: ${Object.keys(modules).join(", ")}`);
