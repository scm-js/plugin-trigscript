// Writes probes/game-fdiv.ts: fixed products and quotients with one side known when the map is built (python/trigscript.py,
// make_const_fdiv and fixed_by_const), each held against the compiler's own arithmetic (compiler/fixedMath.ts) as literals.
//   node scripts/gen-fixed-probe.mjs
import { writeFileSync } from "node:fs";
const U32 = 0x1_0000_0000n;
const mag = (v) => BigInt(v < 0 ? -v : v);
const cell = (m, neg) => Number(BigInt.asIntN(32, (neg ? U32 - (m % U32) : m) % U32));
const fdiv = (a, b) => (b === 0 ? 0 : cell((mag(a) << 16n) / mag(b), (a < 0) !== (b < 0)));
const fmul = (a, b) => cell((mag(a) * mag(b)) >> 16n, (a < 0) !== (b < 0));
const xs = [1, 2, 3, 4, 5, 7, 255, 256, 257, 655, 1000, 32767, 32768, 65535, 65536, 65537, 98304, 131072, 1000000, 16777215, 16777216, 1073741824, 2147483647, -1, -3, -655, -65536, -98304, -16777216, -2147483647, -2147483648, 0];
const lit = (raw) => String(raw / 65536);
// [the constant as written, its raw cell, the operation]
const cases = [
  ["1", 65536, "c/x"], ["3.5", 229376, "c/x"], ["-2", -131072, "c/x"], ["100", 6553600, "c/x"], ["0.0000152587890625", 1, "c/x"], ["30000", 1966080000, "c/x"],
  ["2.5", 163840, "x/c"], ["-0.75", -49152, "x/c"], ["3", 196608, "x/c"], ["0.0000152587890625", 1, "x/c"], ["30000", 1966080000, "x/c"], ["-32768", -2147483648, "x/c"],
  ["0.66", Math.round(0.66 * 65536), "x*c"], ["-2.5", -163840, "x*c"], ["100", 6553600, "x*c"], ["0.0000152587890625", 1, "x*c"], ["32767.9999847412109375", 2147483647, "x*c"], ["-32768", -2147483648, "x*c"],
];
const ys = [1, 3, 655, 32768, 65536, 98304, 1000000, 2147483647, -1, -65536, -1000000, -2147483648];
const want = (c, op) => xs.map((x) => (op === "c/x" ? fdiv(c, x) : op === "x/c" ? fdiv(x, c) : fmul(x, c)));
// (x first into a variable of its own: the cell of the list was read by the Python side, the quotient or the product
// worked out by whatever the build gives it — the emitter's own triggers when the loop is the emitter's.)
const expr = (name, op) => (op === "c/x" ? `${name} / xv` : op === "x/c" ? `xv / ${name}` : `xv * ${name}`);
let src = `// TrigScript 4, the backend, part 3: fixed products and quotients with one side known when the map is built — \`c / x\`,
// \`x / c\`, \`x * c\` (python/trigscript.py, make_const_fdiv and fixed_by_const) — held against the arithmetic the compiler
// does when the map is built (compiler/fixedMath.ts): every result the same bits, for x at the edges (1 to 2^31, both
// signs, 0). Generated by scripts/gen-fixed-probe.mjs: the expected results are literals, each the raw cell over 65 536.
//   npx tsx scripts/test-game.mts probes/game-fdiv.ts
import { test, expect, program, displayText, setResources, gas, sleep, frames, fixed, P1, type fixed as Fixed } from "trigscript";

const xs: Fixed[] = [${xs.map(lit).join(", ")}];
const ys: Fixed[] = [${ys.map(lit).join(", ")}];
`;
cases.forEach(([, c, op], k) => (src += `const want${k}: Fixed[] = [${want(c, op).map(lit).join(", ")}];\n`));
src += `
program(() => {
  setResources(P1, "set", 3, "gas");
  sleep(frames(2));
  const zero = fixed(gas(P1)) - 3; // 0, read in the game
  const none = gas(P1) - 3; // 0 too: the loops' counts are not known when the map is built, so they stay loops
`;
for (const group of ["c/x", "x/c", "x*c"]) {
  src += `  {
    let out = "";
`;
  cases.forEach(([name, , op], k) => {
    if (op !== group) return;
    src += `    {
      let bad = 0, first = -1;
      // (A while loop: a for loop's reads at its counter were the Python side's registers', and the loop with them.)
      let i = none;
      while (i < xs.length + none) {
        const xv: Fixed = xs[i] + zero;
        const q: Fixed = ${expr(name, op)};
        if (q != want${k}[i]) { bad++; if (first < 0) first = i; }
        i++;
      }
      out += \` \${bad}/\${first}\`;
    }
`;
  });
  src += `    displayText(\`${group}:\${out}\`);
    sleep(frames(1));
  }
`;
}
for (const [group, f, e] of [["x*y", fmul, "*"], ["x/y", fdiv, "/"]]) {
  src += `  {
    const want: Fixed[] = [${xs.flatMap((x) => ys.map((y) => lit(f(x, y)))).join(", ")}];
    let bad = 0, first = -1;
    let i = none;
    while (i < xs.length + none) {
      let j = none;
      while (j < ys.length + none) {
        const xv: Fixed = xs[i] + zero, yv: Fixed = ys[j] + zero;
        const q: Fixed = xv ${e} yv;
        if (q != want[i * ys.length + j]) { bad++; if (first < 0) first = i * ys.length + j; }
        j++;
      }
      i++;
    }
    displayText(\`${group}: \${bad}/\${first}\`);
    sleep(frames(1));
  }
`;
}
// Whole numbers, a / b and a % b of two variables (towards zero, the remainder with the dividend's sign).
const as = [0, 1, -1, 2, 7, -7, 100, 1000, -1000, 65536, 2147483647, -2147483648, -2147483647, 123456789];
const bs = [1, -1, 2, 3, 7, -7, 1000, 65537, 2147483647, -2147483648];
const idiv = (a, b) => Number(BigInt.asIntN(32, BigInt(a) / BigInt(b)));
const imod = (a, b) => Number(BigInt.asIntN(32, BigInt(a) % BigInt(b)));
for (const [group, f, e] of [["a/b", idiv, "/"], ["a%b", imod, "%"]]) {
  src += `  {
    const as: number[] = [${as.join(", ")}];
    const bs: number[] = [${bs.join(", ")}];
    const want: number[] = [${as.flatMap((a) => bs.map((b) => f(a, b))).join(", ")}];
    let bad = 0, first = -1;
    let i = none;
    while (i < as.length + none) {
      let j = none;
      while (j < bs.length + none) {
        const av = as[i] + none, bv = bs[j] + none;
        const q = av ${e} bv;
        if (q != want[i * bs.length + j]) { bad++; if (first < 0) first = i * bs.length + j; }
        j++;
      }
      i++;
    }
    displayText(\`${group}: \${bad}/\${first}\`);
    sleep(frames(1));
  }
`;
}
src += `});
`;
for (const group of ["c/x", "x/c", "x*c"]) {
  const n = cases.filter((c) => c[2] === group).length;
  src += `
test("${group}, the same bits as the compiler's", (sim) => {
  sim.frames(12);
  expect(sim).toHavePrinted("${group}:${" 0/-1".repeat(n)}");
});
`;
}
for (const group of ["a/b", "a%b"]) {
  src += `
test("${group} of whole numbers, as the compiler's", (sim) => {
  sim.frames(20);
  expect(sim).toHavePrinted("${group}: 0/-1");
});
`;
}
for (const group of ["x*y", "x/y"]) {
  src += `
test("${group}, the same bits as the compiler's", (sim) => {
  sim.frames(16);
  expect(sim).toHavePrinted("${group}: 0/-1");
});
`;
}
writeFileSync(new URL("../probes/game-fdiv.ts", import.meta.url), src);
